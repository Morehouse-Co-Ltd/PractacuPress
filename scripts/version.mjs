#!/usr/bin/env node
/**
 * Read, check and replace the product version.
 *
 *   node scripts/version.mjs show
 *   node scripts/version.mjs check
 *   node scripts/version.mjs set 1.2.0
 *   node scripts/version.mjs set 1.2.0-beta1
 *   node scripts/version.mjs sync
 *
 * `VERSION` is the only file a person edits. `set` / `sync` then update every
 * checked-in version declaration: the web manifest, npm package + lockfile,
 * the OpenAPI info.version and the generated Go constant.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  normalizeVersion,
  readOpenAPIVersion,
  readPackageLockVersions,
  readProjectVersion,
  replaceFirstVersions,
  stampOpenAPIVersion,
} from './lib/project-version.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const defaultRoot = path.resolve(here, '..');

const args = process.argv.slice(2);
const rootFlag = args.indexOf('--root');
let root = defaultRoot;
if (rootFlag >= 0) {
  root = path.resolve(args[rootFlag + 1] || '');
  args.splice(rootFlag, 2);
}
const command = (args.shift() || 'show').toLowerCase();
const explicit = args.shift() || '';

const files = {
  version: path.join(root, 'VERSION'),
  go: path.join(root, 'internal', 'version', 'version.go'),
  webManifest: path.join(root, 'web', 'public', 'version.json'),
  webPackage: path.join(root, 'web', 'package.json'),
  webLock: path.join(root, 'web', 'package-lock.json'),
  openapi: path.join(root, 'internal', 'packages', 'contracts', 'openapi', 'openapi.yaml'),
};

function fail(message) {
  console.error(`version: ${message}`);
  process.exit(1);
}

function readIfExists(file) {
  return fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
}

function write(file, content) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content, 'utf8');
  console.log(`  ${path.relative(root, file)}`);
}

function readGoVersion() {
  const text = readIfExists(files.go);
  const match = text.match(/var Version = "([^"]+)"/);
  return match ? match[1] : '';
}

function readWebManifest() {
  const text = readIfExists(files.webManifest);
  return text ? JSON.parse(text) : {};
}

function readWebPackage() {
  const text = readIfExists(files.webPackage);
  return text ? JSON.parse(text) : {};
}

function generatedGo(version) {
  return `// Code generated by scripts/version.mjs; DO NOT EDIT.

// Package version identifies the Practacu Press release a binary was built from.
package version

// Version is the product release version. Release builds override it with
// -ldflags "-X github.com/practacu/practacu-press/internal/version.Version=X.Y.Z"
// so a tagged package and a source checkout report the same number.
var Version = "${version}"
`;
}

function collect(expected) {
  const problems = [];

  const rootVersion = readProjectVersion(root);
  if (rootVersion !== expected) {
    problems.push(`VERSION=${rootVersion}, expected ${expected}`);
  }

  const goVersion = readGoVersion();
  if (goVersion !== expected) {
    problems.push(`internal/version/version.go=${goVersion || '(missing)'}, expected ${expected}`);
  }

  const manifest = readWebManifest();
  if (manifest.version !== expected) {
    problems.push(`web/public/version.json=${manifest.version || '(missing)'}, expected ${expected}`);
  }
  if (manifest.style !== normalizeVersion(expected).channel) {
    problems.push(
      `web/public/version.json style=${manifest.style || '(missing)'}, expected ${normalizeVersion(expected).channel}`,
    );
  }

  const webPackage = readWebPackage();
  if (webPackage.version !== expected) {
    problems.push(`web/package.json=${webPackage.version || '(missing)'}, expected ${expected}`);
  }

  const lockVersions = readPackageLockVersions(readIfExists(files.webLock));
  if (lockVersions.length !== 2 || lockVersions.some((value) => value !== expected)) {
    problems.push(
      `web/package-lock.json=${lockVersions.join(', ') || '(missing)'}, expected two ${expected} entries`,
    );
  }

  const contractVersion = readOpenAPIVersion(readIfExists(files.openapi));
  if (contractVersion !== expected) {
    problems.push(`openapi.yaml=${contractVersion || '(missing)'}, expected ${expected}`);
  }

  return problems;
}

function show() {
  const parsed = normalizeVersion(readProjectVersion(root));
  console.log(`version   ${parsed.version}`);
  console.log(`tag       ${parsed.tag}`);
  console.log(`channel   ${parsed.channel}`);
  console.log(`source    ${path.relative(root, files.version)}`);
  console.log(`go        ${readGoVersion() || '(missing)'}`);
  console.log(`manifest  ${readWebManifest().version || '(missing)'}`);
  console.log(`npm       ${readWebPackage().version || '(missing)'}`);
  console.log(`lock      ${readPackageLockVersions(readIfExists(files.webLock)).join(', ') || '(missing)'}`);
  console.log(`openapi   ${readOpenAPIVersion(readIfExists(files.openapi)) || '(missing)'}`);
}

function writeAll(parsed) {
  write(files.version, `${parsed.version}\n`);
  write(files.go, generatedGo(parsed.version));

  const currentManifest = readWebManifest();
  write(
    files.webManifest,
    `${JSON.stringify(
      {
        ...currentManifest,
        version: parsed.version,
        style: parsed.channel,
      },
      null,
      2,
    )}\n`,
  );

  write(files.webPackage, replaceFirstVersions(readIfExists(files.webPackage), parsed.version, 1));
  write(files.webLock, replaceFirstVersions(readIfExists(files.webLock), parsed.version, 2));
  write(files.openapi, stampOpenAPIVersion(readIfExists(files.openapi), parsed.version));
}

function check() {
  const expected = normalizeVersion(readProjectVersion(root)).version;
  const problems = collect(expected);
  if (problems.length > 0) {
    console.error('version: files disagree');
    for (const problem of problems) console.error(`  - ${problem}`);
    console.error('run `node scripts/version.mjs sync` to regenerate them from VERSION');
    process.exit(1);
  }
  console.log(`version: ${expected} is in sync`);
}

try {
  switch (command) {
    case 'show':
      show();
      break;
    case 'check':
      check();
      break;
    case 'set': {
      if (!explicit) fail('set needs a version, for example: node scripts/version.mjs set 1.2.0');
      const parsed = normalizeVersion(explicit);
      console.log(`version: setting ${parsed.version} (${parsed.channel})`);
      writeAll(parsed);
      check();
      break;
    }
    case 'sync': {
      const parsed = normalizeVersion(readProjectVersion(root));
      console.log(`version: syncing ${parsed.version} from VERSION`);
      writeAll(parsed);
      check();
      break;
    }
    case '--help':
    case '-h':
      console.log('usage: version.mjs [show|check|sync|set <version>] [--root <repo>]');
      break;
    default:
      fail(`unknown command: ${command}`);
  }
} catch (error) {
  fail(error.message);
}
